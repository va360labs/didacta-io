import Link from 'next/link';
import { useEffect, useState, type FormEvent } from 'react';
import { useTranslations } from 'next-intl';
import { PasoMarca } from '@/app/welcome/paso-marca';
import {
  AboutField,
  CoverField,
  SocialLinksField,
  draftsFromLinks,
  linksFromDrafts,
  type LinkDraft,
} from '@/components/academy-profile-fields';
import { Icon } from '@/components/icon';
import { ACADEMY_LOCALE_NAMES, ACADEMY_LOCALES, type AcademyLocale } from '@/i18n/config';
import { academyApi, type Academy } from '@/lib/academy';
import { authStorage } from '@/lib/auth-storage';
import { simpleModeApi } from '@/lib/simple-mode';
import {
  publishThemeUpdate,
  themingApi,
  type LogoDisplayMode,
  type TenantTheme,
} from '@/lib/theming';

/** Marca por defecto (la de Didacta): su azul de confianza, tono 213. */
const DIDACTA_HUE = 213;
const DIDACTA_SAT = 70;

/**
 * «Ajustes» del MODO SENCILLO: tu academia (nombre, idioma, logo y color, con
 * vista previa en vivo; y cómo se presenta en la comunidad: portada,
 * descripción y enlaces) y el interruptor para pasar al modo completo. Lo técnico
 * (correo propio, cobros con claves, Zoom, idioma…) sigue en la misma página
 * con `?full=1`, sin rutas duplicadas.
 */
export function SimpleSettings() {
  const t = useTranslations('modoSencilloGestion.ajustes');
  const [academia, setAcademia] = useState<Academy | null>(null);
  const [theme, setTheme] = useState<TenantTheme | null>(null);
  const [nombre, setNombre] = useState('');
  const [idioma, setIdioma] = useState<AcademyLocale>('es');
  const [hue, setHue] = useState(DIDACTA_HUE);
  const [sat, setSat] = useState(DIDACTA_SAT);
  const [modo, setModo] = useState<LogoDisplayMode>('logo_only');
  const [about, setAbout] = useState('');
  const [links, setLinks] = useState<LinkDraft[]>([]);
  const [linksChecked, setLinksChecked] = useState(false);
  const tMarca = useTranslations('adminMarca');
  const [saving, setSaving] = useState(false);
  const [saved, setSaved] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const token = authStorage.getAccessToken();
    if (!token) return;
    void Promise.all([
      academyApi.getMine(token).catch(() => null),
      themingApi.getMine(token).catch(() => null),
    ]).then(([aca, th]) => {
      setAcademia(aca);
      setNombre(aca && !aca.looksAutogenerated ? aca.name : '');
      if (aca) setIdioma(aca.locale);
      if (th) {
        setTheme(th);
        setHue(th.brandHue);
        setSat(th.brandSaturation);
        setModo(th.logoDisplayMode ?? 'logo_only');
        setAbout(th.about ?? '');
        setLinks(draftsFromLinks(th.socialLinks ?? []));
      }
    });
  }, []);

  async function save(e: FormEvent) {
    e.preventDefault();
    const token = authStorage.getAccessToken();
    if (!token) return;
    if (!nombre.trim()) return setError(t('faltaNombre'));
    const enlaces = linksFromDrafts(links);
    if (enlaces.invalid) {
      setLinksChecked(true);
      return setError(tMarca('academyProfile.linksInvalid'));
    }
    setSaving(true);
    setError(null);
    setSaved(false);
    try {
      // Nombre e idioma en una sola llamada, y solo lo que cambia. El idioma se
      // fija también si aún no estaba elegido (solo deducido).
      const cambios = {
        ...(!academia || nombre.trim() !== academia.name ? { name: nombre.trim() } : {}),
        ...(!academia || idioma !== academia.locale || academia.localeSource !== 'setting'
          ? { locale: idioma }
          : {}),
      };
      if (Object.keys(cambios).length > 0) setAcademia(await academyApi.update(token, cambios));
      const actualizado = await themingApi.update(token, {
        brandHue: hue,
        brandSaturation: sat,
        logoDisplayMode: modo,
        about: about.trim() || null,
        socialLinks: enlaces.links,
      });
      setTheme(actualizado);
      setAbout(actualizado.about ?? '');
      setLinks(draftsFromLinks(actualizado.socialLinks));
      setLinksChecked(false);
      publishThemeUpdate(actualizado);
      await simpleModeApi.confirmAcademy();
      window.dispatchEvent(new Event('didacta:empieza-cambio'));
      setSaved(true);
    } catch {
      setError(t('error'));
    } finally {
      setSaving(false);
    }
  }

  async function fullMode() {
    if (!confirm(t('modoConfirmar'))) return;
    try {
      await simpleModeApi.setEnabled(false);
      window.location.assign('/admin');
    } catch {
      setError(t('error'));
    }
  }

  return (
    <div className="mx-auto max-w-[820px]" data-testid="ajustes-sencillo">
      {/* La barra de color de PasoMarca usa estas clases (las mismas del asistente). */}
      <style>{`
        .slider-hue { -webkit-appearance: none; appearance: none; height: 12px; border-radius: 9999px;
          background: linear-gradient(to right, hsl(0 70% 55%), hsl(60 70% 55%), hsl(120 70% 55%), hsl(180 70% 55%), hsl(240 70% 55%), hsl(300 70% 55%), hsl(360 70% 55%)); outline-offset: 4px; }
        .slider-hue::-webkit-slider-thumb { -webkit-appearance: none; appearance: none; width: 22px; height: 22px; border-radius: 9999px;
          background: var(--thumb-color, #333); border: 3px solid white; box-shadow: 0 1px 4px rgb(0 0 0 / 0.35); cursor: pointer; }
        .slider-hue::-moz-range-thumb { width: 22px; height: 22px; border-radius: 9999px; background: var(--thumb-color, #333);
          border: 3px solid white; box-shadow: 0 1px 4px rgb(0 0 0 / 0.35); cursor: pointer; }
      `}</style>
      <h1 className="text-[26px] leading-tight font-extrabold tracking-tight text-text">
        {t('titulo')}
      </h1>
      <p className="mt-1 text-text-muted">{t('sub')}</p>

      <form onSubmit={save} className="mt-6 rounded-2xl border border-border bg-surface p-4 sm:p-6">
        <h2 className="text-lg font-bold text-text">{t('academia')}</h2>
        <label htmlFor="ajustes-nombre" className="mt-4 block text-sm font-semibold text-text">
          {t('nombre')}
        </label>
        <input
          id="ajustes-nombre"
          value={nombre}
          onChange={(e) => setNombre(e.target.value)}
          maxLength={120}
          className="mt-1.5 h-12 w-full rounded-xl border border-border bg-surface px-4 text-[17px] font-semibold text-text outline-none focus:border-brand-600 focus:ring-4 focus:ring-brand-100"
        />
        <p className="mt-1.5 text-sm text-text-subtle">{t('nombreAyuda')}</p>

        <label htmlFor="ajustes-idioma" className="mt-5 block text-sm font-semibold text-text">
          {t('idioma')}
        </label>
        <select
          id="ajustes-idioma"
          value={idioma}
          onChange={(e) => setIdioma(e.target.value as AcademyLocale)}
          className="mt-1.5 h-12 w-full max-w-[280px] rounded-xl border border-border bg-surface px-3 text-base font-semibold text-text outline-none focus:border-brand-600 focus:ring-4 focus:ring-brand-100"
        >
          {ACADEMY_LOCALES.map((l) => (
            <option key={l} value={l} lang={l}>
              {ACADEMY_LOCALE_NAMES[l]}
            </option>
          ))}
        </select>
        <p className="mt-1.5 max-w-[60ch] text-sm text-text-subtle">{t('idiomaAyuda')}</p>

        <h3 className="mt-6 text-[15px] font-bold text-text">{t('marca')}</h3>
        <p className="mt-1 text-sm text-text-muted">{t('marcaAyuda')}</p>
        <div className="mt-4">
          <PasoMarca
            compact
            academia={academia}
            theme={theme}
            hue={hue}
            onHue={setHue}
            sat={sat}
            onSat={setSat}
            modo={modo}
            onModo={setModo}
            onTheme={(th) => {
              setTheme(th);
              publishThemeUpdate(th);
            }}
          />
        </div>

        {/* La tarjeta de la academia en /community, como la de un grupo de
            Skool. La portada se sube al momento, como el logo. */}
        <h3 className="mt-8 text-[15px] font-bold text-text">{t('comunidad')}</h3>
        <p className="mt-1 text-sm text-text-muted">{t('comunidadAyuda')}</p>
        <div className="mt-4 space-y-6" data-testid="ajustes-comunidad">
          <CoverField theme={theme} onTheme={setTheme} />
          <AboutField value={about} onChange={setAbout} />
          <SocialLinksField drafts={links} onChange={setLinks} showErrors={linksChecked} />
        </div>

        {error ? (
          <p role="alert" className="mt-4 text-sm font-semibold text-danger-700">
            {error}
          </p>
        ) : null}
        <div className="mt-6 flex items-center gap-3">
          <button
            type="submit"
            disabled={saving}
            className="h-11 rounded-xl bg-brand-600 px-6 font-semibold text-white hover:bg-brand-700 disabled:opacity-50"
          >
            {saving ? t('guardando') : t('guardar')}
          </button>
          {saved ? (
            <span className="inline-flex items-center gap-1.5 text-sm font-semibold text-success-700">
              <Icon name="check" size={16} />
              {t('guardado')}
            </span>
          ) : null}
        </div>
      </form>

      <Link
        href="/admin/settings?full=1"
        className="mt-4 flex items-center gap-3 rounded-2xl border border-border bg-surface p-4 hover:border-border-strong"
      >
        <Icon name="cog" size={20} />
        <span className="min-w-0 flex-1">
          <span className="block font-semibold text-text">{t('avanzadas')}</span>
          <span className="text-sm text-text-muted">{t('avanzadasAyuda')}</span>
        </span>
        <Icon name="chevron-right" size={16} />
      </Link>

      <section className="mt-4 rounded-2xl bg-bg-subtle p-4 sm:p-5">
        <h2 className="font-bold text-text">{t('modoTitulo')}</h2>
        <p className="mt-1 max-w-[60ch] text-sm text-text-muted">{t('modoTexto')}</p>
        <button
          type="button"
          onClick={() => void fullMode()}
          className="mt-3 h-10 rounded-xl border border-border bg-surface px-4 text-sm font-semibold text-text hover:border-border-strong"
        >
          {t('modoBoton')}
        </button>
      </section>
    </div>
  );
}
