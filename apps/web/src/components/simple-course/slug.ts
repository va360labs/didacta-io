/**
 * Enlace del curso a partir de su título (misma regla que el alta en el
 * servidor): sin acentos, minúsculas y guiones. El creador no lo ve.
 */
export function toSlug(title: string): string {
  const slug = title
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80)
    .replace(/-+$/g, '');
  return slug || 'curso';
}
